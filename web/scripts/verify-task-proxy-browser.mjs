// 真实 Chromium 与合成 HTTP 后端；每个断言等待上限 10 秒，整组目标小于 60 秒。
async (page) => {
  const base = "http://127.0.0.1:4173";
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const evidence = async () => (await page.request.get(`${base}/__fixture/evidence`)).json();
  const control = async (data) => page.request.post(`${base}/__fixture/control`, { data });
  const writes = (value) => value.records.filter((record) => record.method === "PUT");
  const trigger = page.getByRole("button", { name: "切换任务代理", exact: true });
  const save = page.getByRole("button", { name: "保存代理选择", exact: true });
  const mode = page.getByLabel("连接方式", { exact: true });
  const results = [];
  await control({ behavior: {}, task: { proxy_mode: "inherit", proxy_id: 1, proxy: { id: 1, name: "原全局快照", kind: "http" } }, globalID: 2 });
  await page.reload();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await trigger.click();
  await page.getByText("原快照与当前默认不同：", { exact: false }).waitFor();
  check(await mode.inputValue() === "inherit", "原inherit不能改为fixed");
  const before = writes(await evidence()).length;
  await mode.selectOption("direct");
  await page.getByRole("button", { name: "取消", exact: true }).click();
  check(writes(await evidence()).length === before, "取消发出了PUT");
  results.push({ case: "取消", puts: 0 });
  await trigger.click();
  check(await mode.inputValue() === "inherit", "取消草稿不应改变当前模式");
  await mode.selectOption("fixed");
  await page.getByRole("combobox", { name: "代理中心出口", exact: true }).click();
  const search = page.getByPlaceholder("搜索名称、类型、编号或出口 IP…");
  await search.fill("未检测");
  check(await page.getByRole("option", { name: /未检测代理/ }).getAttribute("aria-disabled") === "true", "unknown不应可选");
  await search.fill("203.0.113.4");
  await page.screenshot({ path: "output/verification/task-proxy-switch/search-warp.png", fullPage: true });
  await page.getByRole("option", { name: /搜索 WARP 出口/ }).click();
  await control({ behavior: { delay: 200 } });
  await save.evaluate((button) => { button.click(); button.click(); });
  await page.getByRole("dialog", { name: "切换任务代理", exact: true }).waitFor({ state: "hidden", timeout: 10000 });
  let value = await evidence();
  check(writes(value).length === before + 1, "同事件循环双击不止一次PUT");
  check(value.task.proxy_mode === "fixed" && value.task.proxy_id === 4, "fixed未保存");
  check((await trigger.innerText()).includes("#4"), "徽标未回读fixed");
  check(value.records.some((r, i) => r.method === "GET" && r.mode === "fixed" && i > value.records.findIndex((r) => r.method === "PUT")), "保存后未GET回读");
  results.push({ case: "搜索fixed/双击", puts: 1, mode: "fixed", id: 4 });
  await page.screenshot({ path: "output/verification/task-proxy-switch/saved-fixed.png", fullPage: true });
  for (const selected of ["direct", "inherit"]) {
    await control({ behavior: {} });
    await trigger.click();
    await mode.selectOption(selected);
    await save.click();
    await page.getByRole("dialog", { name: "切换任务代理", exact: true }).waitFor({ state: "hidden", timeout: 10000 });
    value = await evidence();
    check(value.task.proxy_mode === selected, `${selected}未保存`);
    check((await trigger.innerText()).includes(selected === "direct" ? "直连" : "#2"), `${selected}徽标未回读`);
    await trigger.click();
    check(await mode.inputValue() === selected, `${selected}重开回填错误`);
    await page.screenshot({ path: `output/verification/task-proxy-switch/saved-${selected}.png`, fullPage: true });
    await page.getByRole("button", { name: "取消", exact: true }).click();
    results.push({ case: selected, mode: value.task.proxy_mode, id: value.task.proxy_id ?? null });
  }
  await control({ behavior: { saveFailure: 409 } });
  await trigger.click();
  await mode.selectOption("direct");
  await save.click();
  await page.getByText("暂不能切换：", { exact: false }).waitFor();
  check(await mode.inputValue() === "direct", "409丢失用户选择");
  await page.screenshot({ path: "output/verification/task-proxy-switch/conflict-preserves-draft.png", fullPage: true });
  const conflictCount = writes(await evidence()).length;
  await page.getByRole("button", { name: "取消", exact: true }).click();
  check(writes(await evidence()).length === conflictCount, "409自动重试");
  await control({ behavior: { directoryFailure: true } });
  await trigger.click();
  await page.getByText("代理目录加载失败：", { exact: false }).waitFor();
  await mode.selectOption("direct");
  check(await save.isDisabled(), "目录错误静默允许直连保存");
  await page.getByRole("button", { name: "取消", exact: true }).click();
  await control({ behavior: { failReadback: true } });
  await trigger.click();
  await mode.selectOption("direct");
  await save.click();
  const reread = page.getByRole("button", { name: "回读任务核对", exact: true });
  await reread.waitFor();
  const savedCount = writes(await evidence()).length;
  check((await page.locator('button[aria-label="切换任务代理"]').innerText()).includes("待确认"), "回读失败仍显示旧缓存");
  await reread.click();
  await page.getByRole("dialog", { name: "切换任务代理", exact: true }).waitFor({ state: "hidden", timeout: 10000 });
  check(writes(await evidence()).length === savedCount, "回读重试重复PUT");
  check((await trigger.innerText()).includes("直连"), "回读后徽标错误");
  return { synthetic: true, passed: true, results, conflict_preserves_draft: true, directory_fail_closed: true, readback_retry_only_get: true };
}
